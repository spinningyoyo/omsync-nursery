"""What the catalogue says about each scene's animals, birds and effects.

`ELEMENTS` lists, for every scene, the elements the catalogue tables name and the regexes that
find the lines of the scene's module where each one arrives and is drawn. `nursery catalog`
reads it (see nursery.catalog); the nursery-scene skill's catalogue.md says when to change it.
"""

from dataclasses import dataclass


@dataclass
class Element:
    """One animal, bird or effect, and where the code makes it appear and draw.

    `presence` names the instances the stage simulation tracks (such as "monkeys[0]"). Effects
    the simulation cannot see take their stage from `first`, which is typed from the verified
    inventory. Each regex in `arrive` and `draw` is searched in the scene's source, and every line
    it matches is linked, so a changed line shows up as a missing match, not a wrong number.
    """

    label: str
    kind: str  # animal, bird or effect
    sprites: tuple[str, ...]
    fn: str | None = None
    defs: tuple[str, ...] = ()
    defs_label: str = ""
    presence: tuple[str, ...] = ()
    first: int | None = None
    count: tuple[str, str] | None = None  # (regex with one number group, text template)
    fixed: str = ""
    arrive: tuple[str, ...] = ()
    draw: tuple[str, ...] = ()
    layer: str = "in front of the plants"
    sea: bool = False
    module: str = ""  # the kit module that defines `fn` (kit/animals.js), when not the scene


