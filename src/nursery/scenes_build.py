"""Build scenes.json and scenes.css from the scene modules' META declarations.

    uv run nursery scenes [--check]

Evaluates `src/nursery/assets/js/nursery.js` directly in a JS runtime (Node or macOS
JavaScriptCore) so no regexes parse JavaScript source. Derives `scenes.json` and `scenes.css`
from `SCENES` in picker order.
"""

import argparse
import json
import shutil
import subprocess
from pathlib import Path
from typing import Any

from nursery.assets import SCENES_CSS, SCENES_JSON
from nursery.paths import JS_DIR, ROOT

CSS_HEADER = """/*
 * Each scene's colours for the page that hosts it. The host owns the layout and how the colours
 * are used; this file only names them, per scene id.
 *
 * Grid, on :root: --landing-cell, the size of one backdrop grid cell, shared by all scenes.
 *
 * Tint, on [data-tint="<id>"] (the host's <html> while signed in): --scene-tint in light and
 * --scene-tint-dark in dark. The host mixes them into its page background.
 *
 * Backdrop, on [data-scene="<id>"] (the page that shows the scene): the five --landing-* washes,
 * light, then dark under [data-theme="dark"]. The host's backdrop paints them as soft gradients
 * and the scene's bloom.
 *
 * Generated by src/nursery/scenes_build.py from each scene module's META. Rebuild with
 * `uv run nursery scenes`.
 */

/* The size of one grid cell on the page, in CSS pixels: the art's pixel size times its grid
   cell (4px * 16). The host draws its backdrop grid with it. */

:root {
  --landing-cell: 64px;
}
"""

WASH_KEYS = ("green", "green-soft", "peach", "blush", "bloom")

EXPORT_SCRIPT = """
import { SCENES } from "./src/nursery/assets/js/nursery.js";
const out = SCENES.map((s) => ({
  id: s.id,
  label: s.label,
  group: s.group,
  tint: s.tint,
  backdrop: s.backdrop,
}));
const line = JSON.stringify(out);
if (typeof print === "function") print(line);
else console.log(line);
"""


def _js_command() -> list[str]:
    if node := shutil.which("node"):
        return [node, "--input-type=module", "-e", EXPORT_SCRIPT]
    raise RuntimeError(
        f"nursery scenes: needs Node.js (`node`, see README.md) to evaluate {JS_DIR / 'nursery.js'}"
    )


def all_meta() -> list[dict[str, Any]]:
    """Evaluate `nursery.js` in a real JS runtime and return scene metadata in SCENES order."""
    proc = subprocess.run(
        _js_command(),
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    if proc.returncode != 0:
        raise RuntimeError(
            f"nursery scenes: JS evaluation failed ({proc.returncode}): {proc.stderr.strip()}"
        )
    return json.loads(proc.stdout)


def render_scenes_json(metas: list[dict[str, Any]]) -> str:
    rows = [
        f'  {{ "id": {json.dumps(m["id"])}, "label": {json.dumps(m["label"])}, '
        f'"group": {json.dumps(m["group"])} }}'
        for m in metas
    ]
    return "[\n" + ",\n".join(rows) + "\n]\n"


def render_scenes_css(metas: list[dict[str, Any]]) -> str:
    lines = [CSS_HEADER.rstrip(), "", "/* Tints. */", ""]
    for m in metas:
        sid = m["id"]
        light, dark = m["tint"]
        lines += [
            f'[data-tint="{sid}"] {{',
            f"  --scene-tint: {light};",
            f"  --scene-tint-dark: {dark};",
            "}",
        ]
    lines += ["", "/* Backdrops. */", ""]
    for m in metas:
        sid = m["id"]
        for mode, selector in (
            ("light", f'[data-scene="{sid}"]'),
            ("dark", f'[data-theme="dark"] [data-scene="{sid}"]'),
        ):
            washes = m["backdrop"][mode]
            lines.append(f"{selector} {{")
            lines.extend(f"  --landing-{key}: {washes[key]};" for key in WASH_KEYS)
            lines += ["}", ""]
    return "\n".join(lines).rstrip() + "\n"


def built() -> dict[Path, str]:
    metas = all_meta()
    return {
        SCENES_JSON: render_scenes_json(metas),
        SCENES_CSS: render_scenes_css(metas),
    }


def stale() -> list[Path]:
    out = []
    for path, expected in built().items():
        current = path.read_text(encoding="utf-8") if path.is_file() else ""
        if current != expected:
            out.append(path)
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="nursery scenes",
        description="Build scenes.json and scenes.css from the scene modules.",
    )
    parser.add_argument("--check", action="store_true", help="list stale files; change nothing")
    args = parser.parse_args(argv)
    if args.check:
        bad = stale()
        if not bad:
            print("scenes.json and scenes.css match the scene modules")
            return 0
        for path in bad:
            print(f"stale: {path.relative_to(ROOT)}")
        print("run `uv run nursery scenes` to rebuild them")
        return 1
    for path, content in built().items():
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0
