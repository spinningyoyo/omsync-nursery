def free_port() -> int:
    with socket.socket() as sock:
        sock.bind(("127.0.0.1", 0))
        return sock.getsockname()[1]


def start_server(site: Path, port: int, log_path: Path) -> subprocess.Popen:
    """Serve the temporary site in its own process group. Stopped by its pid, never by name."""
    with log_path.open("w") as log:
        return subprocess.Popen(
            [sys.executable, "-m", "http.server", str(port), "--bind", "127.0.0.1"],
            cwd=site,
            stdout=log,
            stderr=subprocess.STDOUT,
            start_new_session=True,
        )


def wait_for_server(proc: subprocess.Popen, url: str, timeout: float = 30) -> None:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if proc.poll() is not None:
            raise RuntimeError("http.server exited early")
        try:
            with urllib.request.urlopen(url, timeout=2) as response:
                if response.status == 200:
                    return
        except OSError:
            pass
        time.sleep(0.2)
    raise RuntimeError(f"http.server did not answer {url}")


def stop_server(proc: subprocess.Popen) -> None:
    try:
        os.killpg(proc.pid, signal.SIGTERM)
    except ProcessLookupError:
        pass
    try:
        proc.wait(timeout=20)
    except subprocess.TimeoutExpired:
        os.killpg(proc.pid, signal.SIGKILL)
        proc.wait()


def new_browser() -> webdriver.Chrome:
    options = webdriver.ChromeOptions()
    options.add_argument("--headless=new")
    options.add_argument("--hide-scrollbars")
    options.add_argument("--force-device-scale-factor=1")
    return webdriver.Chrome(options=options)


def set_viewport(driver: webdriver.Chrome, width: int, height: int) -> None:
    """Make the inner viewport exactly width x height, measured once as the browser chrome."""
    driver.set_window_size(width, height)
    inner = driver.execute_script("return [window.innerWidth, window.innerHeight]")
    if inner != [width, height]:
        driver.set_window_size(width + (width - inner[0]), height + (height - inner[1]))


def write_scene_copies(site: Path) -> None:
    """Copy each scene module into copies/ with its imports rewritten and its functions exported."""
    (site / "copies").mkdir()
    for sid in SCENE_IDS:
        (site / "copies" / f"{sid}.js").write_text(exported_copy(module_path(sid).read_text()))


def exported_copy(text: str) -> str:
    """A scene module with its imports rewritten and its painters and animals exported."""
    names = paint_kinds(text).values()
    names = sorted(set(names) | set(re.findall(r"^function (\w+At)\(", text, re.M)))
    return scene_copy(text) + f"\nexport {{ {', '.join(names)} }};\n"


def paint_kinds(text: str) -> dict[str, str]:
    """The scene's paint map: plant kind to painter function name."""
    match = re.search(r"paint: \{([^}]*)\}", text)
    if not match:
        raise RuntimeError("no paint map in a scene module")
    kinds = {}
    for item in match.group(1).split(","):
        if item.strip():
            kind, _, fn = item.partition(":")
            kinds[kind.strip()] = (fn or kind).strip()
    return kinds


def find_lines(text: str, pattern: str) -> list[int]:
    regex = re.compile(pattern)
    return [n for n, line in enumerate(text.splitlines(), start=1) if regex.search(line)]


def need_line(text: str, pattern: str, what: str) -> int:
    hits = find_lines(text, pattern)
    if not hits:
        raise RuntimeError(f"nursery catalog: no line matches {pattern!r} ({what})")
    return hits[0]


def need_lines(text: str, pattern: str, what: str) -> list[int]:
    hits = find_lines(text, pattern)
    if not hits:
        raise RuntimeError(f"nursery catalog: no line matches {pattern!r} ({what})")
    return hits


def link(name: str, line: int) -> str:
    folder = module_path(name).parent.name
    return f"[L{line}]({SOURCE_LINK}/{folder}/{name}.js#L{line})"


def links(sid: str, lines: list[int]) -> str:
    return ", ".join(link(sid, n) for n in lines)


def describe(text: str) -> str:
    """The first sentence of the file's header comment."""
    header = []
    for line in text.splitlines():
        if not line.startswith("//"):
            break
        header.append(line[2:].strip())
    return " ".join(header).split(". ")[0].rstrip(".") + "."


def layers_text(layers: list[str]) -> str:
    return " / ".join(name for name in LAYER_ORDER if name in layers)


def counts_text(counts: dict[str, int]) -> str:
    return " / ".join(str(counts.get(str(cols), 0)) for cols in (90, 160, 240))


def first_text(stat: list[int]) -> str:
    low, high = stat
    return str(low) if low == high else f"{low}-{high}"


def poses(sid: str, names: tuple[str, ...], drawn: set[str]) -> str:
    """The sprite names the studio shows, marked when the run could not draw one."""
    return ", ".join(
        f"`{name.removeprefix(sid + '-')}`" + ("" if name in drawn else " (not drawn)")
        for name in names
    )


def species_where(sid: str, text: str, painter: str, species: str) -> str:
    hits = find_lines(text, rf"^\s*(?:function\s+)?{re.escape(species)}\s*\(")
    if not hits:
        hits = find_lines(text, rf'species === "{re.escape(species)}"')
    if hits:
        return f"species `{species}` {link(sid, hits[0])}"
    dispatch = need_line(text, rf"^function {painter}\(", f"painter {painter}")
    return f"species `{species}` default branch of `{painter}` {link(sid, dispatch)}"


def plant_rows(sid: str, text: str, data: dict) -> tuple[list[str], list[str]]:
    painters = paint_kinds(text)
    scatter: dict[str, list[int]] = {}
    placed: dict[str, list[int]] = {}
    keep_kinds: list[str] = []
    for match in re.finditer(r"(?:scatter|grove)\(\s*\w+,\s*\w+,\s*\{(.*?)\}\s*\);", text, re.S):
        kind = re.search(r'kind: "(\w+)"', match.group(1))
        if kind:
            scatter.setdefault(kind.group(1), []).append(text.count("\n", 0, match.start()) + 1)
            if "keep:" in match.group(1) and kind.group(1) not in keep_kinds:
                keep_kinds.append(kind.group(1))
    for match in re.finditer(r'makePlant\(\s*\w+,\s*"(\w+)"', text):
        line = text.count("\n", 0, match.start()) + 1
        placed.setdefault(match.group(1), []).append(line)
    sown = {
        kind: scatter.get(kind, []) + placed.get(kind, []) for kind in set(scatter) | set(placed)
    }
    kinds = sorted(sown, key=lambda kind: min(sown[kind]))
    if set(kinds) != set(data["inventory"]):
        raise RuntimeError(f"{sid}: scatter kinds {kinds} do not match the page's inventory")
    rows = []
    for kind in kinds:
        stat = data["inventory"][kind]
        painter = painters[kind]
        painter_line = need_line(text, rf"^function {painter}\(", kind)
        where = [f"painter `{painter}` {link(sid, painter_line)}"]
        if kind in scatter:
            where.append(f"scatter {links(sid, scatter[kind])}")
        if kind in placed:
            where.append(f"placed {links(sid, placed[kind])}")
        rows.append(
            f"| **{kind}** | plant | {first_text(stat['first'])} | "
            f"{counts_text(stat['counts'])} | {layers_text(stat['layers'])} | {'; '.join(where)} |"
        )
        for species in sorted(stat["species"]):
            sub = stat["species"][species]
            rows.append(
                f"| &nbsp;&nbsp;{kind}: {species} | plant | "
                f"{first_text(sub['first'])} | {counts_text(sub['counts'])} | "
                f"{layers_text(sub['layers'])} | {species_where(sid, text, painter, species)} |"
            )
    return rows, keep_kinds


def element_where(sid: str, text: str, el: Element) -> str:
    parts = []
    if el.fn:
        owner = el.module or sid
        owner_text = module_path(owner).read_text()
        line = need_line(owner_text, rf"^(?:export )?function {el.fn}\(", el.label)
        parts.append(f"`{el.fn}` {link(owner, line)}")
    for pattern in el.defs:
        line = need_line(text, pattern, el.label)
        parts.append(f"`{el.defs_label}` {link(sid, line)}")
    if el.arrive:
        lines = sorted({n for p in el.arrive for n in need_lines(text, p, el.label)})
        verb = "starts" if el.kind == "effect" else "arrives"
        parts.append(f"{verb} {links(sid, lines)}")
    if el.draw:
        lines = sorted({n for p in el.draw for n in need_lines(text, p, el.label)})
        parts.append(f"drawn {links(sid, lines)}")
    return "; ".join(parts)


def count_text(text: str, el: Element) -> str:
    if el.fixed:
        return el.fixed
    if el.presence:
        n = len(el.presence)
        return f"{n} instance" + ("" if n == 1 else "s")
    if el.count:
        pattern, template = el.count
        value = re.search(pattern, text)
        if not value:
            raise RuntimeError(f"no count for {el.label}: {pattern!r}")
        return template.format(value.group(1))
    return "1"


def first_stage_text(el: Element, data: dict) -> str:
    if el.presence:
        seen = [(data["presence"][key], key) for key in el.presence if key in data["presence"]]
        if not seen:
            return "never in the run"
        return ", ".join(f"{stage} (`{key}`)" for stage, key in seen)
    return str(el.first)


def timeline_rows(text: str, data: dict, elements: list[Element]) -> list[str]:
    stages: dict[int, dict[str, list[str]]] = {
        s: {"plants": [], "animals": [], "effects": []} for s in range(9)
    }
    for kind, stat in data["inventory"].items():
        stages[stat["first"][0]]["plants"].append(kind)
    for el in elements:
        bucket = "effects" if el.kind == "effect" else "animals"
        if el.presence:
            for key in el.presence:
                if key in data["presence"]:
                    stages[data["presence"][key]][bucket].append(f"{el.label} (`{key}`)")
        elif el.sea:
            sea_rows = int(need_match(text, r"const SEA_ROWS = (\d+)"))
            for s in (1, 2, 3):
                ease = min(1.0, s / 3) ** 2 * (3 - 2 * min(1.0, s / 3))
                stages[s]["effects"].append(f"sea to {round(ease * sea_rows)} rows")
        else:
            stages[el.first][bucket].append(el.label)
    rows = []
    for s, parts in stages.items():
        plants = ", ".join(parts["plants"]) or ("none (bare soil)" if s == 0 else "none")
        animals = ", ".join(parts["animals"]) or "none"
        effects = ", ".join(parts["effects"]) or "none"
        rows.append(f"| {s} | {plants} | {animals} | {effects} |")
    return rows


def need_match(text: str, pattern: str) -> str:
    match = re.search(pattern, text)
    if not match:
        raise RuntimeError(f"no match for {pattern!r}")
    return match.group(1)


def scene_section(sid: str, text: str, data: dict) -> list[str]:
    elements = ELEMENTS[sid]
    plant_table, keep_kinds = plant_rows(sid, text, data)
    out = [
        f"# {SCENE_TITLES[sid]}",
        "",
        f"{describe(text)} Source: [scenes/{sid}.js]({SOURCE_LINK}/scenes/{sid}.js).",
        "",
    ]
    out += [
        "## Stage timeline",
        "",
        "| Stage | New plants | New animals | Effects |",
        "| --- | --- | --- | --- |",
    ]
    out += timeline_rows(text, data, elements) + [""]
    out += [
        "## Elements",
        "",
        "| Element | Kind | First stage | Count at 90 / 160 / 240 px | Layer | Where drawn |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    out += plant_table
    for el in elements:
        drawn = set(data["drawn"])
        out.append(
            f"| {el.label} ({poses(sid, el.sprites, drawn)}) | {el.kind} | "
            f"{first_stage_text(el, data)} | "
            f"{count_text(text, el)} (any width) | {el.layer} | {element_where(sid, text, el)} |"
        )
    out.append("")
    if keep_kinds:
        out.append(
            "Only on wide pages (`keep: middle`, so the middle of the page stays clear): "
            + ", ".join(
                f"`{kind}` ({counts_text(data['inventory'][kind]['counts'])})"
                for kind in keep_kinds
            )
            + ". Counts are at 90 / 160 / 240 px."
        )
        out.append("")
    if data["errors"]:
        out.append("Not drawn: " + "; ".join(data["errors"]) + ".")
        out.append("")
    return out


def scene_markdown(sid: str, result: dict) -> str:
    """One scene's file: its title, a generated-file line and its section, standing alone."""
    text = module_path(sid).read_text()
    lines = scene_section(sid, text, result["scenes"][sid])
    lines[1:1] = ["", HEADER_LINE]
    return "\n".join(lines).rstrip() + "\n"


def write_scene_files(result: dict) -> None:
    """Build every file first, then write them, so a failed run leaves the old files alone.

    A run of all the scenes also removes any other .md in the folder (a scene that is gone);
    a run narrowed with --only writes only its own scenes' files.
    """
    files = {SCENES_DIR / f"{sid}.md": scene_markdown(sid, result) for sid in SCENE_IDS}
    SCENES_DIR.mkdir(parents=True, exist_ok=True)
    for path, content in files.items():
        path.write_text(content)
        print(f"catalogue written to {shown(path)}")
    if not NARROWED:
        for path in sorted(SCENES_DIR.glob("*.md")):
            if path not in files:
                path.unlink()
                print(f"removed stale {shown(path)}")


def check_names(result: dict) -> None:
    """Every pose named in the tables, and every plant kind, must have drawn."""
    for sid in SCENE_IDS:
        drawn = set(result["scenes"][sid]["drawn"])
        for el in ELEMENTS[sid]:
            for name in el.sprites:
                if name not in drawn:
                    print(f"warning: {name} was not drawn ({el.label})", file=sys.stderr)
        for kind in result["scenes"][sid]["inventory"]:
            if f"{sid}-{kind}" not in drawn:
                print(f"warning: {sid}-{kind} was not drawn", file=sys.stderr)


def run_page(base: str) -> dict:
    driver = new_browser()
    try:
        set_viewport(driver, *VIEWPORT)
        driver.get(f"{base}/index.html")
        WebDriverWait(driver, 900, poll_frequency=1).until(
            lambda d: d.execute_script("return window.__status") != "running"
        )
        status = driver.execute_script("return window.__status")
        if status != "done":
            raise RuntimeError(f"catalogue page failed: {status}")
        viewport = driver.execute_script("return [window.innerWidth, window.innerHeight]")
        if list(viewport) != list(VIEWPORT):
            raise RuntimeError(f"viewport was {viewport}, expected {list(VIEWPORT)}")
        return json.loads(driver.execute_script("return JSON.stringify(window.__result)"))
    finally:
        driver.quit()


def shown(path: Path) -> Path:
    try:
        return path.relative_to(ROOT)
    except ValueError:
        return path


def catalog_js() -> str:
    """The page script, with the imports of the scene copies and the scene list filled in."""
    imports = "".join(f'import * as {sid} from "./copies/{sid}.js";\n' for sid in SCENE_IDS)
    copies = f"const COPIES = {{ {', '.join(SCENE_IDS)} }};\nconst IDS = {json.dumps(SCENE_IDS)};"
    return CATALOG_JS.replace("//@COPIES@", imports + copies)


def parse_args(argv: list[str] | None = None) -> None:
    """Narrow the run with --only (a comma-separated scene list) and move the output with --out."""
    global SCENE_IDS, SCENES_DIR, NARROWED
    parser = argparse.ArgumentParser(prog="nursery catalog", description="Catalogue the scenes.")
    parser.add_argument("--only", help="scene ids to run, comma-separated (default: all)")
    parser.add_argument(
        "--out", type=Path, help="write the scene files here (DIR/<id>.md) instead of docs/scenes/"
    )
    args = parser.parse_args(argv)
    if args.only:
        ids = tuple(args.only.split(","))
        unknown = [sid for sid in ids if sid not in SCENE_IDS]
        if unknown:
            parser.error(f"unknown scene ids: {', '.join(unknown)}")
        SCENE_IDS = ids
        NARROWED = True
    if args.out:
        SCENES_DIR = args.out.resolve()


def main(argv: list[str] | None = None) -> None:
    parse_args(argv)
    tmp = Path(tempfile.mkdtemp(prefix="nursery-catalog-"))
    site = tmp / "site"
    site.mkdir()
    (site / "js").symlink_to(JS_DIR)
    shutil.copy(SPRITES_JS, site / "sprites.js")
    write_scene_copies(site)
    (site / "index.html").write_text(INDEX_HTML)
    (site / "catalog.js").write_text(catalog_js())
    port = free_port()
    base = f"http://127.0.0.1:{port}"
    log_path = tmp / "http.log"
    server = start_server(site, port, log_path)
    try:
        wait_for_server(server, f"{base}/index.html")
        print("Running the catalogue page in headless Chrome.")
        result = run_page(base)
    finally:
        stop_server(server)
        shutil.rmtree(tmp, ignore_errors=True)
    for sid in SCENE_IDS:
        data = result["scenes"][sid]
        print(
            f"{sid}: stage-0 pixels above soil (light, dark): "
            f"{data['soil']['light'][0]}, {data['soil']['dark'][0]}"
        )
        print(f"  first stages seen: {data['presence']}")
        for error in data["errors"]:
            print(f"  sprite error: {error}")
    check_names(result)
    write_scene_files(result)
