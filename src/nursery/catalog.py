"""Catalogue the pixel-art scenes: every element and the code that draws it.

    uv run nursery catalog [--only ID,ID] [--out DIR]

--only writes just those scenes' files and deletes nothing; --out DIR writes DIR/<id>.md. A run of
all the scenes removes any other .md in the folder.

The script makes a temporary site: js/ is a symlink to the repository's modules, sprites.js
(studio/shared/sprites.js) poses every element, and copies/ holds the scene modules with their
painter and animal functions exported (the repository's files are not edited). It serves the
site with `python -m http.server` and loads it in headless Chrome. The page samples each scene at
90, 160 and 240 px wide, draws every plant kind, species and pose once to check that it draws, and
runs a real Nursery, seeded with a fixed seed for each scene and theme so every run gives the
same tables, through stages 0 to 8 in light and dark. It writes one file per scene,
docs/scenes/<id>.md, with the line numbers read from the source when it runs. Pictures are
left to the Nursery Studio (src/nursery/studio/server.py), which draws them from the code.
The server and the browser are stopped by their process ids, and the temporary directory is
removed.
"""

